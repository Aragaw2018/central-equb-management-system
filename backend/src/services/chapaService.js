// backend/src/services/chapaService.js
'use strict';

const axios = require('axios');

const CHAPA_BASE_URL = 'https://api.chapa.co/v1';

/**
 * Pre-configured Axios instance for all Chapa API calls.
 * - Bearer token from CHAPA_SECRET_KEY env var
 * - 15-second timeout to avoid hanging requests
 * - JSON content type enforced
 */
const chapaClient = axios.create({
    baseURL: CHAPA_BASE_URL,
    timeout: 15_000,
    headers: {
        'Content-Type': 'application/json',
        Authorization:  `Bearer ${process.env.CHAPA_SECRET_KEY}`,
    },
});

// ── Request logger (dev/debug) ─────────────────────────────────────────────────
chapaClient.interceptors.request.use((config) => {
    console.log(`[Chapa ▶] ${config.method?.toUpperCase()} ${config.baseURL}${config.url}`);
    return config;
});

// ── Response logger ────────────────────────────────────────────────────────────
chapaClient.interceptors.response.use(
    (response) => {
        console.log(`[Chapa ◀] ${response.status} ${response.config.url} →`, response.data?.status);
        return response;
    },
    (error) => {
        const status  = error.response?.status;
        const message = error.response?.data?.message || error.message;
        console.error(`[Chapa ✖] ${status || 'NETWORK_ERR'} — ${message}`);
        return Promise.reject(error);
    }
);

/**
 * Initialize a Chapa payment transaction.
 *
 * @param {Object} params
 * @param {number|string} params.amount         - Contribution amount in ETB
 * @param {string}        params.currency       - ISO currency code (default: 'ETB')
 * @param {string}        params.email          - Payer's email (required by Chapa)
 * @param {string}        params.firstName      - Payer's first name
 * @param {string}        params.lastName       - Payer's last/father name
 * @param {string}        params.tx_ref         - Unique transaction reference (generated by caller)
 * @param {string}        params.callback_url   - Chapa server-to-server webhook URL (optional)
 * @param {string}        params.return_url     - Redirect URL after payment on Chapa's hosted page
 *
 * @returns {{ checkoutUrl: string, tx_ref: string }}
 * @throws  Will throw with a descriptive message if Chapa rejects the request
 */
async function initializePayment({
    amount,
    currency    = 'ETB',
    email,
    firstName,
    lastName,
    tx_ref,
    callback_url,
    return_url,
}) {
    if (!amount || !email || !tx_ref || !return_url) {
        throw new Error('Chapa initializePayment: amount, email, tx_ref, and return_url are required.');
    }

    const payload = {
        amount:       String(amount),
        currency,
        email,
        first_name:   firstName,
        last_name:    lastName,
        tx_ref,
        return_url,
        ...(callback_url && { callback_url }),
        // Customisation fields shown on Chapa's hosted checkout page
        title:        'Equb Contribution',
        description:  `Equb payment — Ref: ${tx_ref}`,
    };

    console.log(`[Chapa] Initializing payment | tx_ref=${tx_ref} | amount=${amount} ${currency}`);

    const { data } = await chapaClient.post('/transaction/initialize', payload);

    if (data.status !== 'success') {
        throw new Error(`Chapa initialization failed: ${data.message || JSON.stringify(data)}`);
    }

    return {
        checkoutUrl: data.data.checkout_url,
        tx_ref,
    };
}

/**
 * Verify the status of a Chapa transaction.
 *
 * @param {string} tx_ref  - The unique transaction reference to verify
 *
 * @returns {Object}  Full Chapa transaction data object
 * @throws  Will throw if the transaction is not found or network errors occur
 */
async function verifyPayment(tx_ref) {
    if (!tx_ref) throw new Error('Chapa verifyPayment: tx_ref is required.');

    console.log(`[Chapa] Verifying payment | tx_ref=${tx_ref}`);

    const { data } = await chapaClient.get(`/transaction/verify/${encodeURIComponent(tx_ref)}`);

    if (data.status !== 'success') {
        throw new Error(`Chapa verification failed: ${data.message || JSON.stringify(data)}`);
    }

    // data.data contains the full transaction object from Chapa
    return data.data;
}

module.exports = { initializePayment, verifyPayment };
